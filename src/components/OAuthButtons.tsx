export function OAuthButtons({ className = "" }: { className?: string }) {
  const navigate = useNavigate();
  const [loading, setLoading] = useState<string | null>(null);

  const go = (provider: string) => {
    setLoading(provider);
    setTimeout(() => navigate({ to: "/onboarding" }), 900);
  };

  const providers = [
    { id: "google", label: "Continue with Google", Icon: GoogleIcon },
    { id: "apple", label: "Continue with Apple", Icon: AppleIcon },
    { id: "github", label: "Continue with GitHub", Icon: GithubIcon },
  ];

  return (
    <div className={`space-y-2 ${className}`}>
      {providers.map((p) => (
        <button
          key={p.id}
          onClick={() => go(p.id)}
          disabled={loading !== null}
          className="surface flex h-10 w-full items-center justify-center gap-2.5 rounded-lg text-sm font-medium transition-colors hover:bg-secondary disabled:opacity-60"
        >
          {loading === p.id ? <Loader2 className="h-4 w-4 animate-spin" /> : <p.Icon className="h-4 w-4" />}
          {p.label}
        </button>
      ))}
    </div>
  );
}
